const routesFixes = new Set<string>(routesIllustrees);
const routesAvecParametres = routesIllustrees
  .filter(route => route.includes("["))
  .map(route => ({ route, segments: route.split("/") }));

export function visuelEspace(chemin: string): string | null {
  const route = chemin.replace(/\/+$/, "");
  const segments = route.split("/");
  const modele = routesFixes.has(route) ? route : routesAvecParametres.find(candidat =>
    candidat.segments.length === segments.length && candidat.segments.every((segment, i) =>
      segment === segments[i] || (segment.startsWith("[") && segments[i].length > 0)
    )
  )?.route;
  return modele ? `/visuels/espace${modele.replaceAll("/", "-").replace(/[\[\]]/g, "")}.webp` : null;
}
